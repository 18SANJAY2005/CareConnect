export const calculateAdminMetrics = (
  elders: AdminElderItem[],
  caregivers: AdminCaregiverItem[],
  alerts: AdminSosAlert[]
): AdminMetrics => {
  const totalElders = elders.length;
  const activeCareShifts = caregivers.filter((c) => c.status === 'ON_DUTY').length;
  const openSosTickets = alerts.filter((a) => a.status === 'OPEN' || a.status === 'DISPATCHED').length;
  const verifiedCaregivers = caregivers.filter((c) => c.isClinicalCertified).length;
  const bufferPoolAvailable = caregivers.filter((c) => (c.isBufferPool || c.isStandbyReserve) && c.status === 'AVAILABLE').length;

  const totalAttendants = caregivers.length;
  const activeAttendants = activeCareShifts;
  const inactiveAttendants = Math.max(0, totalAttendants - activeAttendants);

  return {
    totalElders,
    activeCareShifts,
    serviceableCorridors: serviceableCorridors.length,
    openSosTickets,
    verifiedCaregivers,
    bufferPoolAvailable,
    totalAttendants,
    activeAttendants,
    inactiveAttendants,
  };
};

