/**
 * Great-circle geodetic distance in kilometers (Haversine Formula)
 */
export const calculateDistanceKm = (
  lat1: number,
  lon1: number,
  lat2: number,
  lon2: number
): number => {
  const R = 6371; // Earth's mean radius in km
  const dLat = ((lat2 - lat1) * Math.PI) / 180;
  const dLon = ((lon2 - lon1) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((lat1 * Math.PI) / 180) *
      Math.cos((lat2 * Math.PI) / 180) *
      Math.sin(dLon / 2) *
      Math.sin(dLon / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return Math.round(R * c * 10) / 10;
};

/**
 * Calculates nearby hospitals from the catalog for given coordinates
 */
export const getNearbyHospitalsForCoordinates = (
  lat: number,
  lon: number,
  limit: number = 4
): NearbyHospital[] => {
  return initialHospitalCatalog
    .map((hosp) => {
      const distance = calculateDistanceKm(lat, lon, hosp.latitude ?? lat, hosp.longitude ?? lon);
      const etaMins = Math.max(3, Math.round(distance * 2.8) + 2);
      return {
        ...hosp,
        distanceKm: distance,
        etaMins,
        googleMapsUrl: hosp.googleMapsUrl || (hosp.latitude && hosp.longitude ? `https://maps.google.com/?q=${hosp.latitude},${hosp.longitude}` : undefined),
      };
    })
    .sort((a, b) => a.distanceKm - b.distanceKm)
    .slice(0, limit);
};

/**
 * Retrieves hospitals near a care seeker's home based on their locality (e.g. Adyar, Anna Nagar, T. Nagar, etc.)
 */
export const getHospitalsForLocality = (
  localityOrAddress: string,
  elderLat?: number,
  elderLon?: number
): NearbyHospital[] => {
  const norm = (localityOrAddress || '').toUpperCase();
  let baseHospitals: NearbyHospital[] = [];

  if (norm.includes('BESANT')) baseHospitals = standardChennaiHospitals.BESANT_NAGAR;
  else if (norm.includes('ANNA')) baseHospitals = standardChennaiHospitals.ANNA_NAGAR;
  else if (norm.includes('T. NAGAR') || norm.includes('T NAGAR')) baseHospitals = standardChennaiHospitals.T_NAGAR;
  else if (norm.includes('MYLAPORE')) baseHospitals = standardChennaiHospitals.MYLAPORE;
  else if (norm.includes('VELACHERY')) baseHospitals = standardChennaiHospitals.VELACHERY;
  else if (norm.includes('OMR') || norm.includes('PERUNGUDI')) baseHospitals = standardChennaiHospitals.OMR;
  else baseHospitals = standardChennaiHospitals.ADYAR;

  if (elderLat && elderLon) {
    return baseHospitals
      .map((hosp) => {
        const dist = calculateDistanceKm(elderLat, elderLon, hosp.latitude ?? elderLat, hosp.longitude ?? elderLon);
        const eta = Math.max(3, Math.round(dist * 2.8) + 2);
        return {
          ...hosp,
          distanceKm: dist,
          etaMins: eta,
          googleMapsUrl: hosp.googleMapsUrl || (hosp.latitude && hosp.longitude ? `https://maps.google.com/?q=${hosp.latitude},${hosp.longitude}` : undefined),
        };
      })
      .sort((a, b) => a.distanceKm - b.distanceKm);
  }

  return baseHospitals;
};

/**
 * Returns Google Maps driving navigation URL from careseeker home to hospital
 */
export const getGoogleMapsDirectionsUrl = (
  originLat: number,
  originLon: number,
  destLat: number,
  destLon: number
): string => {
  return `https://www.google.com/maps/dir/?api=1&origin=${originLat},${originLon}&destination=${destLat},${destLon}&travelmode=driving`;
};

/**
 * Returns Google Maps search URL for a hospital
 */
export const getGoogleMapsSearchUrl = (name: string, lat?: number, lon?: number): string => {
  if (lat && lon) {
    return `https://www.google.com/maps/search/?api=1&query=${lat},${lon}`;
  }
  return `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(name + ' Hospital Chennai')}`;
};

